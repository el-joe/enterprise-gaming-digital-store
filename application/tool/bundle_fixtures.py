#!/usr/bin/env python3
"""Compiles test/fixtures/api/**/*.json into integration_test/fixtures/api_fixtures.g.dart.

The integration suite (M-A19) runs on an emulator or device, where the fixture files under
test/fixtures/api are not on the file system. The fake repositories read them through
ApiFixture.load, which uses this map when ApiFixture.bundle is set.

    python3 tool/bundle_fixtures.py          write the Dart file
    python3 tool/bundle_fixtures.py --check  exit 1 when the Dart file is stale

Run from anywhere; paths are relative to the application directory. tool/ci.sh runs --check.
"""

import json
import pathlib
import sys

APP = pathlib.Path(__file__).resolve().parent.parent
SOURCE = APP / "test" / "fixtures" / "api"
TARGET = APP / "integration_test" / "fixtures" / "api_fixtures.g.dart"


def dart_string(text: str) -> str:
    """A single-quoted Dart string literal of [text] (JSON escapes are valid Dart escapes)."""
    # json.dumps escapes backslashes, quotes, control and non-ASCII characters; Dart reads the
    # same escapes. Then swap the quotes and escape what is special to Dart only.
    body = json.dumps(text)[1:-1]
    body = body.replace('\\"', '"').replace("'", "\\'").replace("$", "\\$")
    return "'" + body + "'"


def render() -> str:
    names = sorted(
        str(path.relative_to(SOURCE).with_suffix("")).replace("\\", "/")
        for path in SOURCE.rglob("*.json")
    )
    lines = [
        "// GENERATED by tool/bundle_fixtures.py from test/fixtures/api. Do not edit.",
        "// Regenerate after tool/sync_fixtures.sh: python3 tool/bundle_fixtures.py",
        "",
        "/// Every contract fixture as JSON text, by name (for example `catalog/products_en`).",
        "const apiFixtureBundle = <String, String>{",
    ]
    for name in names:
        text = (SOURCE / f"{name}.json").read_text(encoding="utf-8")
        # Re-encode compactly: the same JSON value, smaller source.
        compact = json.dumps(json.loads(text), ensure_ascii=False, separators=(",", ":"))
        lines.append(f"  '{name}': {dart_string(compact)},")
    lines.append("};")
    return "\n".join(lines) + "\n"


def main() -> int:
    content = render()
    if len(sys.argv) > 1 and sys.argv[1] == "--check":
        if not TARGET.exists() or TARGET.read_text(encoding="utf-8") != content:
            print(
                "integration_test/fixtures/api_fixtures.g.dart is stale. "
                "Run 'python3 tool/bundle_fixtures.py'.",
                file=sys.stderr,
            )
            return 1
        print(f"Fixture bundle in sync ({content.count(chr(10)) - 6} fixtures).")
        return 0
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(content, encoding="utf-8")
    print(f"Wrote {TARGET.relative_to(APP)} ({len(content) // 1024} KiB).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
